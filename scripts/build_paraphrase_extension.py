def overlap(question: str, text: str) -> float:
    """问题的双字集合里，有多少比例也出现在片段里。"""
    grams = set(tokenize_text(question, "cjk_bigram"))
    return len(grams & set(tokenize_text(text, "cjk_bigram"))) / max(len(grams), 1)


def sample_order(chunks: list[dict], queries: list[dict]) -> list[str]:
    gold = {g for q in queries for g in q["gold_evidence_ids"]}
    pool = sorted(c["chunk_id"] for c in chunks if c["chunk_id"] not in gold)
    return random.Random(SEED).sample(pool, len(pool))


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def build(chunks: list[dict], queries: list[dict], judgments: list[dict]) -> list[dict]:
    text = {c["chunk_id"]: c["text"] for c in chunks}
    twins: dict[str, list[str]] = {}
    for c in chunks:
        twins.setdefault(c["text"], []).append(c["chunk_id"])
    order = sample_order(chunks, queries)
    if max(ANSWERABLE) >= ANSWERABLE_SAMPLES or min(NEAR_MISS) < ANSWERABLE_SAMPLES:
        raise ValueError("可回答问题与没有对应证据的问题必须取自抽样序列的不同区段")
    extra: dict[str, set[str]] = {}
    for row in judgments:
        if row["human_label"] == "answers":
            extra.setdefault(row["sample_id"], set()).add(row["chunk_id"])
    rows = []
    for i, question in ANSWERABLE.items():
        if question is None:
            continue
        anchor = order[i]
        value = overlap(question, text[anchor])
        if value > MAX_OVERLAP:
            raise ValueError(f"{i} 与锚定片段的双字重合率 {value:.2f} 超过 {MAX_OVERLAP}")
        sample_id = f"pv3x_P_{i:03d}"
        gold = set(twins[text[anchor]]) | extra.get(sample_id, set())
        rationale = f"抽样锚定 {anchor}，双字重合率 {value:.2f}"
        added = sorted(gold - set(twins[text[anchor]]))
        if added:
            rationale += f"；经人工复核补充 {', '.join(added)}"
        rows.append({"sample_id": sample_id, "split": "test", "bucket": "paraphrase", "question": question,
                     "gold_evidence_ids": sorted(gold), "rationale": rationale + "。", "origin": ORIGIN})
    for i, (question, rationale, _terms) in NEAR_MISS.items():
        sample_id = f"pv3x_N_{i:03d}"
        if sample_id in extra:
            raise ValueError(f"{sample_id} 是没有对应证据的问题，复核却给出了正确片段")
        rows.append({"sample_id": sample_id, "split": "test", "bucket": "near_miss", "question": question,
                     "gold_evidence_ids": [], "rationale": rationale, "origin": ORIGIN})
    known = {r["sample_id"] for r in rows}
    unknown = set(extra) - known
    if unknown:
        raise ValueError(f"复核记录引用了不存在的问题：{sorted(unknown)}")
    return rows


def near_miss_sheet(chunks: list[dict], queries: list[dict]) -> str:
    """人工核查用：每条没有对应证据的问题，列出 BM25 前 5 段与含核查词（第一个是主题词，不参与）的全部片段。"""
    from medidiag.rag.retrieval import Bm25Retriever
    from medidiag.schemas import KnowledgeChunk

    retriever = Bm25Retriever([KnowledgeChunk(**c) for c in chunks], "cjk_bigram")
    retriever.build_index()
    text = {c["chunk_id"]: c["text"] for c in chunks}
    order = sample_order(chunks, queries)
    lines = []
    for i, (question, rationale, terms) in NEAR_MISS.items():
        lines.append(f"== pv3x_N_{i:03d}（锚定 {order[i]}）{question}\n   理由：{rationale}")
        hits = {hit.chunk_id for hit in retriever.search(question, top_k=5)}
        hits |= {cid for cid, body in text.items() if any(t in body for t in terms[1:])}
        lines.extend(f"    {cid} {text[cid]}" for cid in sorted(hits))
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true", help="覆盖已有的 queries.jsonl")
    parser.add_argument("--near-miss-sheet", type=Path, default=None, help="另写一份没有对应证据问题的人工核查表")
    args = parser.parse_args()
    chunks = read_jsonl(SOURCE / "chunks.jsonl")
    if args.near_miss_sheet:
        args.near_miss_sheet.write_text(near_miss_sheet(chunks, read_jsonl(SOURCE / "queries.jsonl")), encoding="utf-8")
    judgments_path = TARGET / "pooled_judgments.jsonl"
    judgments = read_jsonl(judgments_path) if judgments_path.exists() else []
    rows = build(chunks, read_jsonl(SOURCE / "queries.jsonl"), judgments)
    content = "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows)
    target = TARGET / "queries.jsonl"
    if target.exists() and not args.write and target.read_text(encoding="utf-8") != content:
        raise SystemExit(f"{target} 与重新生成的内容不同；确认后用 --write 覆盖")
    TARGET.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(SOURCE / "chunks.jsonl", TARGET / "chunks.jsonl")  # 语料与 v3 逐字节相同
    target.write_text(content, encoding="utf-8", newline="\n")
    print(f"可回答 {sum(1 for r in rows if r['gold_evidence_ids'])} 条，没有对应证据 "
          f"{sum(1 for r in rows if not r['gold_evidence_ids'])} 条；queries.jsonl sha256 "
          f"{hashlib.sha256(target.read_bytes()).hexdigest()}")


if __name__ == "__main__":
    main()
